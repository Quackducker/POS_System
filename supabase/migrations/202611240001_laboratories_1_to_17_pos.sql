create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text,
  role text not null default 'Cashier' check (role in ('Administrator', 'Manager', 'Cashier', 'Inventory Staff'))
);

create table if not exists public.products (
  product_id bigint generated by default as identity primary key,
  product_code text unique not null,
  product_name text not null,
  category text,
  price numeric(12,2) not null check (price >= 0),
  cost numeric(12,2) not null default 0 check (cost >= 0),
  quantity integer not null default 0 check (quantity >= 0),
  reorder_level integer not null default 0 check (reorder_level >= 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

create table if not exists public.customers (
  customer_id bigint generated by default as identity primary key,
  customer_code text unique,
  customer_name text not null,
  contact_number text,
  email text,
  address text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

create table if not exists public.sales (
  sale_id bigint generated by default as identity primary key,
  transaction_no text unique not null,
  customer_id bigint references public.customers(customer_id),
  cashier_id uuid references auth.users(id),
  cashier_name text,
  sale_date timestamptz not null default now(),
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  tax numeric(12,2) not null default 0,
  total_amount numeric(12,2) not null,
  status text not null default 'Completed' check (status in ('Completed', 'Cancelled'))
);

create table if not exists public.sale_items (
  sale_item_id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(sale_id) on delete cascade,
  product_id bigint not null references public.products(product_id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null,
  subtotal numeric(12,2) not null
);

create table if not exists public.payments (
  payment_id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(sale_id) on delete cascade,
  payment_method text not null,
  amount_received numeric(12,2) not null,
  change_amount numeric(12,2) not null default 0,
  payment_date timestamptz not null default now()
);

create index if not exists sales_sale_date_idx on public.sales(sale_date desc);
create index if not exists sale_items_sale_id_idx on public.sale_items(sale_id);
create index if not exists payments_sale_id_idx on public.payments(sale_id);

