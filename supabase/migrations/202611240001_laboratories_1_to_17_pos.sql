create or replace function public.process_sale(
  p_customer_id bigint,
  p_items jsonb,
  p_discount numeric,
  p_tax numeric,
  p_payment_method text,
  p_amount_received numeric,
  p_cashier_name text default 'Cashier'
)
returns table(sale_id bigint, transaction_no text, subtotal numeric, discount numeric, tax numeric, total_amount numeric, change_amount numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sale_id bigint;
  v_transaction_no text;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := greatest(coalesce(p_discount, 0), 0);
  v_tax numeric(12,2) := greatest(coalesce(p_tax, 0), 0);
  v_total numeric(12,2);
  v_change numeric(12,2);
  v_item jsonb;
  v_product public.products%rowtype;
begin
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Cart is empty.';
  end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    select * into v_product
    from public.products
    where product_id = (v_item->>'product_id')::bigint
    for update;

    if not found then
      raise exception 'Product not found.';
    end if;
    if v_product.status <> 'Active' then
      raise exception 'Product % is inactive.', v_product.product_name;
    end if;
    if (v_item->>'quantity')::integer < 1 then
      raise exception 'Quantity must be at least 1.';
    end if;
    if v_product.quantity < (v_item->>'quantity')::integer then
      raise exception 'Insufficient stock for %. Available: %, Requested: %.',
        v_product.product_name, v_product.quantity, (v_item->>'quantity')::integer;
    end if;

    v_subtotal := v_subtotal + (v_product.price * (v_item->>'quantity')::integer);
  end loop;

  v_total := greatest(v_subtotal - v_discount + v_tax, 0);
  if coalesce(p_amount_received, 0) < v_total then
    raise exception 'Insufficient payment. Total: %, Received: %.', v_total, p_amount_received;
  end if;
  v_change := coalesce(p_amount_received, 0) - v_total;

  v_transaction_no := 'POS-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.sales_sale_id_seq')::text, 5, '0');

  insert into public.sales (
    transaction_no, customer_id, cashier_name, subtotal, discount, tax, total_amount, status
  ) values (
    v_transaction_no, p_customer_id, p_cashier_name, v_subtotal, v_discount, v_tax, v_total, 'Completed'
  ) returning public.sales.sale_id into v_sale_id;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    select * into v_product
    from public.products
    where product_id = (v_item->>'product_id')::bigint
    for update;

    insert into public.sale_items (sale_id, product_id, quantity, unit_price, subtotal)
    values (
      v_sale_id,
      v_product.product_id,
      (v_item->>'quantity')::integer,
      v_product.price,
      v_product.price * (v_item->>'quantity')::integer
    );

    update public.products
    set quantity = quantity - (v_item->>'quantity')::integer
    where product_id = v_product.product_id;
  end loop;

  insert into public.payments (sale_id, payment_method, amount_received, change_amount)
  values (v_sale_id, p_payment_method, p_amount_received, v_change);

  return query
  select v_sale_id, v_transaction_no, v_subtotal, v_discount, v_tax, v_total, v_change;
end;
$$;

grant execute on function public.process_sale(bigint, jsonb, numeric, numeric, text, numeric, text) to anon, authenticated;

